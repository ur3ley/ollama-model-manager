// Offline self-test for the Modelfile parsing helpers used by the editor.
//
// Extracts TEMPLATE / RENDERER / PARSER / FROM from the text produced by
// `ollama show --modelfile`, including triple-quoted multi-line templates.
//
//   ./modelfile-parse-selftest            → PASS/FAIL lines, exit 0/1
//   ./modelfile-parse-selftest FILE       → dump parsed fields for FILE

#include "modelfilebuilder.h"
#include "ollamacli.h"

#include <QCoreApplication>
#include <QFile>
#include <QTextStream>

namespace {

int g_failures = 0;

void check(bool condition, const QString &what)
{
    QTextStream out(stdout);
    out << (condition ? "PASS " : "FAIL ") << what << "\n";
    if (!condition)
        ++g_failures;
}

void checkEqual(const QString &actual, const QString &expected, const QString &what)
{
    const bool ok = actual == expected;
    QTextStream out(stdout);
    out << (ok ? "PASS " : "FAIL ") << what;
    if (!ok)
        out << " (got '" << actual << "', expected '" << expected << "')";
    out << "\n";
    if (!ok)
        ++g_failures;
}

} // namespace

int main(int argc, char *argv[])
{
    QCoreApplication app(argc, argv);

    if (argc > 1) {
        QFile f(QString::fromLocal8Bit(argv[1]));
        if (!f.open(QIODevice::ReadOnly)) {
            QTextStream(stdout) << "cannot open file\n";
            return 1;
        }
        const QString content = QString::fromUtf8(f.readAll());
        QTextStream out(stdout);
        out << "from      [" << OllamaCli::extractFromBase(content) << "]\n"
            << "renderer  [" << OllamaCli::extractDirective(content, QStringLiteral("RENDERER")) << "]\n"
            << "parser    [" << OllamaCli::extractDirective(content, QStringLiteral("PARSER")) << "]\n"
            << "template  [" << OllamaCli::extractDirective(content, QStringLiteral("TEMPLATE")) << "]\n";
        return 0;
    }

    // Typical `ollama show --modelfile` output: comments, FROM, a triple-quoted
    // Go template, RENDERER, a licence block.
    const QString full = QStringLiteral(
        "# Modelfile generated by \"ollama show\"\n"
        "# To build a new Modelfile based on this, replace FROM with:\n"
        "# FROM my-model:latest\n"
        "\n"
        "FROM /var/lib/ollama/blobs/sha256-abc\n"
        "TEMPLATE \"\"\"{{- if .System }}<|im_start|>system\n"
        "{{ .System }}<|im_end|>\n"
        "{{ end }}{{- range .Messages }}<|im_start|>{{ .Role }}\n"
        "{{ .Content }}<|im_end|>{{- end }}<|im_start|>assistant\n"
        "\"\"\"\n"
        "RENDERER qwen3.5\n"
        "PARSER qwen3.5\n"
        "SYSTEM \"\"\"\nBe brief.\n\"\"\"\n"
        "LICENSE \"\"\"MIT\n\"\"\"\n");

    checkEqual(OllamaCli::extractFromBase(full), QStringLiteral("my-model:latest"),
               QStringLiteral("FROM taken from the comment"));
    checkEqual(OllamaCli::extractDirective(full, QStringLiteral("RENDERER")),
               QStringLiteral("qwen3.5"), QStringLiteral("RENDERER parsed"));
    checkEqual(OllamaCli::extractDirective(full, QStringLiteral("PARSER")),
               QStringLiteral("qwen3.5"), QStringLiteral("PARSER parsed"));

    const QString tpl = OllamaCli::extractDirective(full, QStringLiteral("TEMPLATE"));
    check(!tpl.isEmpty(), QStringLiteral("TEMPLATE parsed"));
    check(tpl.startsWith(QLatin1String("{{- if .System }}")), QStringLiteral("TEMPLATE starts correctly"));
    check(tpl.endsWith(QLatin1String("<|im_start|>assistant")), QStringLiteral("TEMPLATE ends correctly"));
    check(!tpl.contains(QLatin1String("LICENSE")), QStringLiteral("TEMPLATE does not leak into the licence"));

    // Real `ollama show --modelfile` output closes the template on the same
    // line as its last character: `{{- end }}"""`.
    const QString inlineClose = QStringLiteral(
        "FROM m\n"
        "TEMPLATE \"\"\"{{- if .System }}sys\n{{ .Content }}{{- end }}\"\"\"\n"
        "RENDERER qwen3.5\n");
    checkEqual(OllamaCli::extractDirective(inlineClose, QStringLiteral("TEMPLATE")),
               QStringLiteral("{{- if .System }}sys\n{{ .Content }}{{- end }}"),
               QStringLiteral("closing quotes on the last line"));
    checkEqual(OllamaCli::extractDirective(inlineClose, QStringLiteral("RENDERER")),
               QStringLiteral("qwen3.5"),
               QStringLiteral("directive after an inline-closed template"));

    // Model without an explicit template: Ollama prints a one-liner.
    const QString autoTpl = QStringLiteral(
        "FROM my-model:latest\n"
        "TEMPLATE {{ .Prompt }}\n");
    checkEqual(OllamaCli::extractDirective(autoTpl, QStringLiteral("TEMPLATE")),
               QStringLiteral("{{ .Prompt }}"), QStringLiteral("single-line TEMPLATE parsed"));
    checkEqual(OllamaCli::extractDirective(autoTpl, QStringLiteral("RENDERER")),
               QString(), QStringLiteral("missing directive gives empty string"));

    // Case sensitivity: directive names are upper-case in Modelfiles.
    const QString lower = QStringLiteral("FROM x\nrenderer qwen3\n");
    checkEqual(OllamaCli::extractDirective(lower, QStringLiteral("RENDERER")),
               QString(), QStringLiteral("lower-case directive is not matched"));

    // ModelfileBuilder: SYSTEM survives a build → extract round trip verbatim
    // (blank lines, indentation), which the `ollama show` System section does not.
    {
        ModelfileBuilder::Config config;
        config.from = QStringLiteral("qwen3:8b");
        config.enableSystemPrompt = true;
        config.systemPrompt = QStringLiteral("Line one\n\n    indented code\nlast");
        QString error = QStringLiteral("stale");
        const QString built = ModelfileBuilder::build(config, &error);
        check(error.isEmpty(), QStringLiteral("builder: valid config gives no error"));
        checkEqual(OllamaCli::extractDirective(built, QStringLiteral("SYSTEM")),
                   config.systemPrompt, QStringLiteral("builder: SYSTEM round trip is verbatim"));
        OllamaCli::ModelParams params;
        OllamaCli::applyModelfile(params, built);
        checkEqual(params.systemPrompt, config.systemPrompt,
                   QStringLiteral("applyModelfile: SYSTEM taken from the Modelfile"));

        // `"""` inside a block would end it early: the build is refused.
        config.systemPrompt = QStringLiteral("Example:\n\"\"\"\nPARAMETER temperature 2\n\"\"\"");
        const QString broken = ModelfileBuilder::build(config, &error);
        check(broken.isEmpty(), QStringLiteral("builder: SYSTEM with triple quotes refused"));
        checkEqual(error, QStringLiteral("SYSTEM"), QStringLiteral("builder: error names SYSTEM"));

        // A disabled SYSTEM is not written, so its content does not matter.
        config.enableSystemPrompt = false;
        check(!ModelfileBuilder::build(config, &error).isEmpty() && error.isEmpty(),
              QStringLiteral("builder: disabled SYSTEM is not validated"));

        config.templateStr = QStringLiteral("{{ .Prompt }} \"\"\"");
        check(ModelfileBuilder::build(config, &error).isEmpty()
                      && error == QLatin1String("TEMPLATE"),
              QStringLiteral("builder: TEMPLATE with triple quotes refused"));
    }

    // B-8: blob FROM lines are recognised under any storage root.
    checkEqual(OllamaCli::blobFromModelfile(full), QStringLiteral("/var/lib/ollama/blobs/sha256-abc"),
               QStringLiteral("blob FROM: system install"));
    checkEqual(OllamaCli::blobFromModelfile(
                       QStringLiteral("# c\nFROM /home/u/.ollama/models/blobs/sha256-0f\nPARAMETER a 1\n")),
               QStringLiteral("/home/u/.ollama/models/blobs/sha256-0f"),
               QStringLiteral("blob FROM: user install"));
    checkEqual(OllamaCli::blobFromModelfile(QStringLiteral("FROM qwen3:8b\n")), QString(),
               QStringLiteral("blob FROM: model reference is not a blob"));
    checkEqual(OllamaCli::modelsDirFromBlob(QStringLiteral("/srv/models/blobs/sha256-ab")),
               QStringLiteral("/srv/models"), QStringLiteral("models dir from blob path"));
    checkEqual(OllamaCli::modelsDirFromBlob(QString()), QString(),
               QStringLiteral("models dir: empty blob"));

    QTextStream(stdout) << (g_failures == 0 ? "ALL OK\n"
                                            : "FAILURES: " + QString::number(g_failures) + "\n");
    return g_failures == 0 ? 0 : 1;
}
