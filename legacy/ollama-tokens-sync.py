#!/usr/bin/env python3
"""Sync Ollama API tokens from KDE Wallet into an nginx map snippet.

Source of truth: KWallet wallet "kdewallet", folder "ollama-auth".
  key   = device name (nout, android, ...)
  value = token
  key   = "created:<device>", value = ISO-8601 creation timestamp

Output: $XDG_RUNTIME_DIR/ollama-auth/maps.conf (tmpfs, 0700/0600).
Nothing secret is ever written to disk; the file disappears on logout/reboot.

Usage:
  ollama-tokens-sync.py            # regenerate snippet only
  ollama-tokens-sync.py --reload   # regenerate + nginx -t + nginx -s reload
"""

import argparse
import os
import re
import subprocess
import sys

WALLET = "kdewallet"
FOLDER = "ollama-auth"
APP_ID = "ollama-tokens-sync"
CREATED_PREFIX = "created:"
CONTAINER = "ollama-auth"
KDE_SERVICE = "org.kde.kwalletd6"
KDE_PATH = "/modules/kwalletd6"
KDE_IFACE = "org.kde.KWallet"

TOKEN_RE = re.compile(r"^[A-Za-z0-9._~+/=-]{16,200}$")


def log(msg: str) -> None:
    print(f"[tokens-sync] {msg}", flush=True)


def qdbus(method: str, *args: str) -> str:
    """Call a kwalletd6 DBus method through qdbus6 and return raw stdout."""
    cmd = ["qdbus6", KDE_SERVICE, KDE_PATH, f"{KDE_IFACE}.{method}", *args]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(
            f"qdbus6 {method} failed rc={res.returncode}: {res.stderr.strip() or res.stdout.strip()}"
        )
    return res.stdout.strip()


def wallet_is_open() -> bool:
    try:
        return qdbus("isOpen", WALLET) == "true"
    except Exception as exc:
        log(f"kwalletd not reachable: {exc}")
        return False


def open_wallet() -> int:
    handle = int(qdbus("open", WALLET, "0", APP_ID))
    if handle < 0:
        raise RuntimeError(f"cannot open wallet '{WALLET}' (handle={handle})")
    return handle


def read_tokens(handle: int) -> dict:
    """Return {device: token}, ignoring malformed entries."""
    raw = qdbus("entryList", str(handle), FOLDER, APP_ID)
    names = [n for n in raw.splitlines() if n.strip()]
    tokens = {}
    for name in names:
        if name.startswith(CREATED_PREFIX):
            continue
        value = qdbus("readPassword", str(handle), FOLDER, name, APP_ID)
        if not value:
            log(f"skip '{name}': empty value")
            continue
        if not TOKEN_RE.match(value):
            log(f"skip '{name}': token contains unsupported characters")
            continue
        tokens[name] = value
    return tokens


def render(tokens: dict) -> str:
    lines = [
        "# Generated by ollama-tokens-sync.py -- DO NOT EDIT.",
        f"# Source: KDE Wallet '{WALLET}', folder '{FOLDER}'.",
        f"# Devices: {', '.join(sorted(tokens)) if tokens else '(none)'}",
        "",
        "map $http_authorization $om_dev_bearer {",
        '    default "";',
    ]
    for dev in sorted(tokens):
        lines.append(f'    "Bearer {tokens[dev]}" "{dev}";')
    lines += ["}", "", "map $http_x_api_key $om_dev_key {", '    default "";']
    for dev in sorted(tokens):
        lines.append(f'    "{tokens[dev]}" "{dev}";')
    lines += ["}", ""]
    return "\n".join(lines)


def runtime_dir() -> str:
    base = os.environ.get("XDG_RUNTIME_DIR") or f"/run/user/{os.getuid()}"
    path = os.path.join(base, "ollama-auth")
    os.makedirs(path, mode=0o700, exist_ok=True)
    os.chmod(path, 0o700)
    return path


def write_snippet(content: str) -> tuple:
    """Write snippet; return (path, changed)."""
    directory = runtime_dir()
    target = os.path.join(directory, "maps.conf")
    try:
        with open(target, encoding="utf-8") as fh:
            if fh.read() == content:
                return target, False
    except FileNotFoundError:
        pass
    tmp = target + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(tmp, 0o600)
    os.replace(tmp, target)
    return target, True


def container_running() -> bool:
    res = subprocess.run(
        ["podman", "inspect", "-f", "{{.State.Running}}", CONTAINER],
        capture_output=True,
        text=True,
    )
    return res.returncode == 0 and res.stdout.strip() == "true"


def reload_nginx() -> None:
    if not container_running():
        log("container not running, skipping reload")
        return
    test = subprocess.run(
        ["podman", "exec", CONTAINER, "nginx", "-t"], capture_output=True, text=True
    )
    if test.returncode != 0:
        raise RuntimeError(f"nginx -t failed: {test.stderr.strip() or test.stdout.strip()}")
    reload_res = subprocess.run(
        ["podman", "exec", CONTAINER, "nginx", "-s", "reload"], capture_output=True, text=True
    )
    if reload_res.returncode != 0:
        raise RuntimeError(
            f"nginx reload failed: {reload_res.stderr.strip() or reload_res.stdout.strip()}"
        )
    log("nginx reloaded")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reload", action="store_true", help="reload nginx after rendering")
    args = parser.parse_args()

    target = os.path.join(runtime_dir(), "maps.conf")

    if wallet_is_open():
        try:
            handle = open_wallet()
            tokens = read_tokens(handle)
        except Exception as exc:
            log(f"wallet read failed ({exc}); leaving snippet untouched")
            return 1
    else:
        # Never open a locked wallet from a background job: that pops a prompt.
        if os.path.exists(target):
            log("wallet locked, snippet left untouched")
            return 0
        log("wallet locked and no snippet yet, writing deny-all snippet")
        tokens = {}

    path, changed = write_snippet(render(tokens))
    log(
        f"{'wrote' if changed else 'unchanged'} {path} "
        f"with {len(tokens)} token(s): {', '.join(sorted(tokens)) or 'none'}"
    )

    if args.reload and changed:
        try:
            reload_nginx()
        except Exception as exc:
            log(f"reload failed: {exc}")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
